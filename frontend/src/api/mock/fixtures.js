// ── CATEGORY FILTER HELPER ───────────────────────────────────
// Single source of truth for filtering — used by both MSW handlers
// and axiosMock. No more brittle name arrays.
export function filterMenuByCategory(items, category) {
  if (!category || category === 'all') return items
  if (category === 'today_special') return items.filter(i => i.is_today_special)
  return items.filter(i => i.ui_category === category)
}

// ── SLOT BUILDER ─────────────────────────────────────────────
// Build slots relative to the current time so there are always open slots
// regardless of time of day (important for demos and testing)
function buildSlots() {
  const now = new Date()
  const dateStr = now.toISOString().split('T')[0]
  const slots = []

  // Generate 12 slots: starting 30 min from now, each 15 minutes wide
  const baseTime = new Date(now)
  baseTime.setMinutes(baseTime.getMinutes() + 30, 0, 0)

  for (let i = 0; i < 12; i++) {
    const start = new Date(baseTime.getTime() + i * 15 * 60 * 1000)
    const end = new Date(start.getTime() + 15 * 60 * 1000)
    const cutoff = new Date(start.getTime() - 30 * 60 * 1000)

    const fmt = (d) => `${String(d.getHours()).padStart(2,'0')}:${String(d.getMinutes()).padStart(2,'0')}`

    slots.push({
      id: i + 1,
      date: dateStr,
      start_time: fmt(start),
      end_time: fmt(end),
      cutoff_time: cutoff.toISOString(),
    })
  }
  return slots
}

export const SLOTS = buildSlots()

// ── SLOT CAPACITIES ──────────────────────────────────────────
export const SLOT_CAPACITIES = (() => {
  const caps = []
  let capId = 1
  SLOTS.forEach(slot => {
    MENU_ITEMS.forEach(item => {
      const maxUnits = item.category === 'ready_stock' ? 50 : 20
      const isNearCap = item.id === 4 && slot.id === 6  // Vadapav in slot 6 — near capacity demo
      caps.push({
        id: capId++,
        slot_id: slot.id,
        menu_item_id: item.id,
        max_units: isNearCap ? 2 : maxUnits,
        units_booked: isNearCap ? 1 : 0,
      })
    })
  })
  return caps
})()

// ── MOCK ORDERS ───────────────────────────────────────────────
export let ORDERS = []
let orderIdCounter = 1

export function createMockOrder({ user_id, slot_id, items }) {
  const slot = SLOTS.find(s => s.id === slot_id)
  const orderItems = items.map((i, idx) => {
    const item = MENU_ITEMS.find(m => m.id === i.menu_item_id)
    return {
      id: idx + 1,
      menu_item_id: i.menu_item_id,
      menu_item: item,
      quantity: i.quantity,
      price_at_order: item.price,
    }
  })
  const total = orderItems.reduce(
    (sum, oi) => sum + Number(oi.price_at_order) * oi.quantity,
    0
  )
  const tokenNumber = ORDERS.filter(o => o.slot_id === slot_id).length + 1
  const order = {
    id: orderIdCounter++,
    user_id,
    slot_id,
    slot,
    status: 'placed',
    payment_status: 'pending',
    total_amount: total.toFixed(2),
    razorpay_payment_id: null,
    token_number: tokenNumber,
    qr_token: `mock-qr-token-${orderIdCounter}`,
    created_at: new Date().toISOString(),
    items: orderItems,
  }
  ORDERS.push(order)
  return order
}

